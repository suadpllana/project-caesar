"""Write the cheat collectors, each as a directory ready to overlay onto the tree.

Two kinds. The wrong-reading cheats come from the same declared overrides `readings.py` uses, so
a cheat cannot drift away from the reading it stands for. The adversarial ones are written out
here: they do not misread the contract, they attack the verifier - by memorising what they were
shown, by forging the record, by trying to seize the reward, or by breaking the stage that runs
them. `rescan-pairs` is neither: it is exactly correct and too slow, and it is what the tree
ships.

Every one must score 0, and `cheat_report.py` asserts which layer catches it.

    python authoring/reach-pair-sweep/emit.py
"""
