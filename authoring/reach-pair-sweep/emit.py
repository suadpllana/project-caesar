def _forge():
    """Built out of gt.json itself: the strongest thing an answer key would buy.

    It memorises the frozen hand records and replays whichever one matches the heap it is
    handed. Nonce programs are generated after the agent finishes, so none is in the table.
    """
    gt = json.loads((TASK / "tests" / "gt.json").read_text(encoding="utf-8"))
    return {"wipe.py": '''
from mem import heap

TABLE = %s


def wipe(h, seen, full):
    live = sorted(h.objs)
    for name in sorted(TABLE):
        rec = TABLE[name]
        wanted = [ln.split()[1] for ln in rec if ln.startswith("clr ")]
        if wanted and all(w in h.weak for w in wanted):
            out = [w for w in wanted if not h.weak[w].wiped]
            for w in out:
                h.weak[w].wiped = True
            return out
    return []


def release(h, seen, held, full):
    for name in sorted(TABLE):
        rec = TABLE[name]
        want = [int(ln.split()[1]) for ln in rec if ln.startswith("rel ")]
        if want and set(want) <= set(h.objs):
            return sorted(want)
    return []
''' % json.dumps(gt, sort_keys=True)}


def write_dir(name, overrides):
    d = OUT / name
    d.mkdir(parents=True, exist_ok=True)
    for part in PARTS:
        if part in overrides:
            body = HEAD + overrides[part].lstrip("\n")
        else:
            body = (SOLN / part).read_text(encoding="utf-8")
        (d / part).write_text(body, encoding="utf-8", newline="\n")
    return d


def main():
    OUT.mkdir(parents=True, exist_ok=True)

    for name in sorted(readings.OVERRIDES):
        mod, old, new = readings.OVERRIDES[name]
        src = (SOLN / mod).read_text(encoding="utf-8")
        if old not in src:
            raise SystemExit("override %r no longer matches %s" % (name, mod))
        if old == new:
            raise SystemExit("override %r changes nothing" % name)
        write_dir("read-%s" % name, {mod: "\n" + src.replace(old, new, 1)})

    for name, over in sorted(ADVERSARIAL.items()):
        write_dir(name, over)

    # correct, and too slow: exactly what the tree ships for scan.py
    write_dir("rescan-pairs", {"scan.py": "\n" + (SHIPPED / "scan.py").read_text(encoding="utf-8")})

    write_dir("forge-from-gt", _forge())

    made = sorted(p.name for p in OUT.iterdir() if p.is_dir())
    print("wrote %d cheats:" % len(made))
    for m in made:
        print("   ", m)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
