TASK = pathlib.Path(__file__).resolve().parent.parent
REF = TASK / "solution" / "ref" / "route.py"
DEST = "/app/view/route.py"


def heredoc(path: str, body: str) -> str:
    return "mkdir -p \"$(dirname %s)\"\ncat > %s <<'EOF_ROUTE'\n%s\nEOF_ROUTE\n" % (
        path, path, body.rstrip("\n"))


def anchor(src: str) -> str:
    return src[src.index("    def _absorbable"):]


