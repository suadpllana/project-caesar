def main() -> int:
    ref = REF.read_text()
    anc = anchor(ref)

    solve = TASK / "solution" / "solve.sh"
    solve.write_text(
        "#!/bin/bash\n"
        "# Reference solution. Writes the corrected router and re-runs the engine so the\n"
        "# result is computed by the code, never echoed.\n"
        "set -euo pipefail\n\n"
        + heredoc(DEST, ref)
        + "\ncd /app\npython - <<'EOF_CHECK'\n"
        "import json, sys\n"
        "sys.path.insert(0, '/app')\n"
        "from view import drv\n"
        "cfg = json.load(open('/app/conf/view.json'))\n"
        "d = drv.Drv(cfg)\n"
        "r = d.run([{'op': 'ins', 'src': 'ord', 'k': 'a', 'g': 'g1', 'v': 5, 'ts': 1},\n"
        "           {'op': 'del', 'src': 'ord', 'k': 'a', 'ts': 3}])\n"
        "print('view', json.dumps(r['view'], sort_keys=True))\n"
        "print('folds', r['folds'], 'scans', r['scans'])\n"
        "EOF_CHECK\n",
        newline="\n")

    cheat = TASK / "cheat"
    cheat.mkdir(exist_ok=True)
    made = []
    for name, (why, body) in MISTAKES.items():
        src = ref.replace(anc, body)
        p = cheat / ("cheat-%s.sh" % name)
        p.write_text("#!/bin/bash\n# %s\nset -euo pipefail\n\n" % why + heredoc(DEST, src),
                     newline="\n")
        made.append(p.name)
    for name, (why, body) in PROBES.items():
        p = cheat / ("cheat-%s.sh" % name)
        p.write_text("#!/bin/bash\n# %s\nset -euo pipefail\n\n" % why + heredoc(DEST, body),
                     newline="\n")
        made.append(p.name)

    (cheat / "README.md").write_text(
        "# Cheat suite\n\n"
        "Every script here must score 0. Two families:\n\n"
        "**Single-mistake variants** are the whole reference solution with exactly one\n"
        "decision made the way a solver who missed one piece would make it. They are\n"
        "generated from `solution/ref/route.py` by `authoring/emit.py`, so they always\n"
        "carry the rest of the fix and test only the mistake they name. The interesting\n"
        "ones produce every value correctly and fail on the work counters alone.\n\n"
        "**Isolation probes** are built on the shipped tree and attack the verifier\n"
        "rather than the problem: a backgrounded reward write, a planted run output, a\n"
        "planted output followed by a hard exit, wrong-typed junk from the report,\n"
        "forged counters, a privilege probe, a ground-truth read and a sweep of\n"
        "everything the run's uid can reach.\n\n"
        "Regenerate with `python3 authoring/emit.py`. Do not hand-edit these files.\n",
        newline="\n")

    print("wrote solve.sh and %d cheats" % len(made))
    for n in sorted(made):
        print("  ", n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
